from typing import Any

from support import RecoveryTestEnv, claude_record, previews, write_claude_transcript


def recover_claude(recovery_env: RecoveryTestEnv, records: list[dict[str, object]], session_id: str = "claude-1") -> dict[str, Any]:
    write_claude_transcript(recovery_env, session_id, records)
    return recovery_env.recovery.recover(str(recovery_env.workspace), source_provider="claude", session_id=session_id)


def test_tool_results_are_not_user_messages(recovery_env: RecoveryTestEnv) -> None:
    result = recover_claude(
        recovery_env,
        [
            claude_record(recovery_env, "user", "fix the flaky test"),
            claude_record(
                recovery_env,
                "assistant",
                [
                    {"type": "text", "text": "Running it"},
                    {"type": "tool_use", "id": "t1", "name": "Bash", "input": {"command": "pytest"}},
                ],
            ),
            claude_record(
                recovery_env,
                "user",
                [{"type": "tool_result", "tool_use_id": "t1", "content": "1 failed"}],
                toolUseResult={"stdout": "1 failed"},
            ),
            claude_record(recovery_env, "assistant", [{"type": "text", "text": "Fixed the race"}]),
        ],
    )

    assert previews(result["recent_user_messages"]) == ["fix the flaky test"]
    assert [tool["name"] for tool in result["recent_tool_uses"]] == ["Bash"]


def test_meta_and_wrapper_noise_is_dropped(recovery_env: RecoveryTestEnv) -> None:
    result = recover_claude(
        recovery_env,
        [
            claude_record(
                recovery_env,
                "user",
                "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>",
                isMeta=True,
            ),
            claude_record(
                recovery_env,
                "user",
                "<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>",
            ),
            claude_record(recovery_env, "user", "<local-command-stdout></local-command-stdout>"),
            claude_record(recovery_env, "user", "<task-notification>\n<task-id>abc</task-id>\n</task-notification>"),
            claude_record(
                recovery_env,
                "user",
                [
                    {"type": "text", "text": "<system-reminder>\nbe careful\n</system-reminder>"},
                    {"type": "text", "text": "Refactor auth to use JWT"},
                ],
            ),
        ],
    )

    assert previews(result["recent_user_messages"]) == ["/clear", "Refactor auth to use JWT"]
    assert result["initial_user_prompt"]["text"] == "Refactor auth to use JWT"
    assert result["preview"] == "Refactor auth to use JWT"


def test_updated_at_tracks_last_activity(recovery_env: RecoveryTestEnv) -> None:
    write_claude_transcript(
        recovery_env,
        "early-start",
        [
            claude_record(recovery_env, "user", "old task", timestamp="2026-10-01T09:00:00Z", session_id="early-start"),
            claude_record(
                recovery_env,
                "assistant",
                [{"type": "text", "text": "still going"}],
                timestamp="2026-10-05T17:00:00Z",
                session_id="early-start",
            ),
        ],
    )
    write_claude_transcript(
        recovery_env,
        "late-start",
        [claude_record(recovery_env, "user", "newer task", timestamp="2026-10-03T09:00:00Z", session_id="late-start")],
    )

    result = recovery_env.recovery.discover(str(recovery_env.workspace), source_provider="claude")

    assert [(candidate["session_id"], candidate["updated_at"]) for candidate in result["candidates"]] == [
        ("early-start", "2026-10-05T17:00:00Z"),
        ("late-start", "2026-10-03T09:00:00Z"),
    ]


def test_assistant_messages_keep_their_reasoning_text(recovery_env: RecoveryTestEnv) -> None:
    long_text = " ".join(["I chose JWT over server sessions because the API must stay stateless."] * 8)
    result = recover_claude(
        recovery_env,
        [
            claude_record(recovery_env, "user", "Refactor auth"),
            claude_record(recovery_env, "assistant", [{"type": "text", "text": long_text}]),
        ],
    )

    entry = result["recent_assistant_messages"][-1]
    assert entry.get("text") == long_text
    assert entry.get("truncated") is False
    assert len(entry["preview"]) <= 160
    assert "window" not in entry


def test_very_long_messages_are_bounded(recovery_env: RecoveryTestEnv) -> None:
    huge = "x" * 50_000
    result = recover_claude(
        recovery_env,
        [
            claude_record(recovery_env, "user", "Refactor auth"),
            claude_record(recovery_env, "assistant", [{"type": "text", "text": huge}]),
        ],
    )

    entry = result["recent_assistant_messages"][-1]
    assert entry.get("truncated") is True
    assert len(entry.get("text") or "") < len(huge)


def test_thinking_blocks_are_recovered_as_reasoning(recovery_env: RecoveryTestEnv) -> None:
    result = recover_claude(
        recovery_env,
        [
            claude_record(recovery_env, "user", "Refactor auth"),
            claude_record(
                recovery_env,
                "assistant",
                [{"type": "thinking", "thinking": "Sessions need sticky storage; JWT avoids that.", "signature": "sig"}],
            ),
            claude_record(recovery_env, "assistant", [{"type": "thinking", "thinking": "", "signature": "sig"}]),
            claude_record(recovery_env, "assistant", [{"type": "text", "text": "Going with JWT"}]),
        ],
    )

    assert [entry["text"] for entry in result.get("recent_reasoning", [])] == [
        "Sessions need sticky storage; JWT avoids that."
    ]


def test_compaction_summary_is_kept_out_of_user_messages(recovery_env: RecoveryTestEnv) -> None:
    summary = "This session is being continued from a previous conversation. Summary: chose JWT over sessions."
    result = recover_claude(
        recovery_env,
        [
            claude_record(recovery_env, "user", "Refactor auth"),
            claude_record(recovery_env, "user", summary, isCompactSummary=True, isVisibleInTranscriptOnly=True),
            claude_record(recovery_env, "user", "keep going"),
        ],
    )

    assert (result.get("compaction_summary") or {}).get("text") == summary
    assert previews(result["recent_user_messages"]) == ["Refactor auth", "keep going"]
